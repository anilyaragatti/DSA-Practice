package bitManipulation;

public class binaryAnd {

    public static void main(String[] args) {
        System.out.println((5 & 6)); //Bit-wise AND
        System.out.println((5 | 6)); //Bit-wise OR
        System.out.println((5 ^ 6)); //Bit-wise XOR
        System.out.println((~5));//once Complement
        System.out.println(5<<2);//Binry Left-Shift
        System.out.println(6>>1);//Binary Rigth-Shift

    }
}
